/**
 * Zoekt een icoon op naam op. Onbekende of lege naam -> `fallback`.
 *
 * @param name   Iconennaam uit config- of registry-data (bijv. 'Radar').
 * @param fallback Icoon dat gerenderd wordt als `name` niet in de registry staat.
 */
export function resolveIcon(name: string | null | undefined, fallback: LucideIcon): LucideIcon {
  if (!name) return fallback;
  return ICONS[name] ?? fallback;
}
